/**
 * Test-case traceability: keep docs/test-cases.md and the code in step.
 *
 * Usage:
 *   node tests/tc-index.mjs           check (run by tests/run.mjs)
 *   node tests/tc-index.mjs --write   regenerate the index block in the doc
 *
 * Rules (docs/test-cases.md §1):
 * 1. Every `check('TC-…')` / `todo('TC-…')` id is unique across the repository.
 * 2. The block between the INDEX markers equals what this script generates.
 * 3. Every `todo` id has a spec section `### TC-… ` in the doc.
 * 4. A spec section's `状态` matches the code: `todo` → a todo() call,
 *    `auto` → a check() call, `manual` → no code at all.
 * 5. Every `TASK-NN` named in lib/ or tests/ has a `## TASK-NN` card in
 *    docs/tasks.md.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const DOC = path.join(ROOT, 'docs', 'test-cases.md')
const TASKS = path.join(ROOT, 'docs', 'tasks.md')
const BEGIN = '<!-- TC-INDEX:BEGIN (generated by `node tests/tc-index.mjs --write`; do not edit by hand) -->'
const END = '<!-- TC-INDEX:END -->'

/** Display order of areas in the index. */
const AREA_ORDER = ['CORE', 'OPS', 'REG', 'DSP', 'INS', 'TGT', 'HOST', 'DIR', 'CLIENT', 'STAMP', 'PATCH', 'ARCH', 'PACK', 'DEPLOY', 'E2E']

const sourceFiles = [
  ...readdirSync(path.join(ROOT, 'tests'))
    .filter((name) => name.endsWith('.mjs') && name !== 'harness.mjs' && name !== 'tc-index.mjs')
    .map((name) => `tests/${name}`),
  'scripts/pack-check.mjs',
]

/** Collect every case declared in code. */
function collect() {
  const cases = []
  const pattern = /^\s*(?:await\s+)?(check|todo)\('(TC-[A-Z][A-Z0-9]*-\d{3})',\s*(['`])((?:\\.|(?!\3).)*)\3/gm
  for (const file of sourceFiles) {
    const text = readFileSync(path.join(ROOT, file), 'utf8')
    for (const match of text.matchAll(pattern)) {
      cases.push({ id: match[2], kind: match[1] === 'check' ? 'auto' : 'todo', name: match[4].replace(/\\'/g, "'"), file })
    }
  }
  return cases
}

/** Sort key: area order, then number. */
function order(a, b) {
  const [, areaA, numA] = a.id.split('-')
  const [, areaB, numB] = b.id.split('-')
  const rank = (area) => (AREA_ORDER.includes(area) ? AREA_ORDER.indexOf(area) : AREA_ORDER.length)
  return rank(areaA) - rank(areaB) || areaA.localeCompare(areaB) || Number(numA) - Number(numB)
}

/** Render the generated index block. */
function render(cases, specs) {
  const rows = [...cases]
  for (const spec of specs.values()) {
    if (spec.status === 'manual') rows.push({ id: spec.id, kind: 'manual', name: spec.title, file: '(manual)' })
  }
  rows.sort(order)
  const lines = [BEGIN, '', '| ID | 状态 | 用例 | 位置 |', '|---|---|---|---|']
  for (const row of rows) lines.push(`| ${row.id} | ${row.kind} | ${row.name.replace(/\|/g, '\\|')} | ${row.file} |`)
  const counts = { auto: 0, todo: 0, manual: 0 }
  for (const row of rows) counts[row.kind] += 1
  lines.push('', `合计 ${rows.length}：auto ${counts.auto}，todo ${counts.todo}，manual ${counts.manual}。`, '', END)
  return lines.join('\n')
}

/** Parse `### TC-… title` spec sections and their `状态` lines. */
function readSpecs(doc) {
  const specs = new Map()
  const sections = doc.split(/^### /m).slice(1)
  for (const section of sections) {
    const heading = /^(TC-[A-Z][A-Z0-9]*-\d{3})\s+(.+)$/m.exec(section)
    if (heading === null) continue
    const status = /^-\s*状态[:：]\s*(auto|todo|manual)\b/m.exec(section)?.[1]
    specs.set(heading[1], { id: heading[1], title: heading[2].trim(), status })
  }
  return specs
}

const problems = []
const cases = collect()
const doc = readFileSync(DOC, 'utf8').replace(/\r\n/g, '\n')
const specs = readSpecs(doc)

// Rule 1.
const seen = new Map()
for (const item of cases) {
  if (seen.has(item.id)) problems.push(`duplicate id ${item.id} in ${seen.get(item.id)} and ${item.file}`)
  seen.set(item.id, item.file)
}
const byId = new Map(cases.map((item) => [item.id, item]))

// Rules 3 and 4.
for (const item of cases) {
  if (item.kind === 'todo' && !specs.has(item.id)) problems.push(`${item.id} is a todo without a spec section in docs/test-cases.md`)
}
for (const spec of specs.values()) {
  if (spec.status === undefined) {
    problems.push(`${spec.id} spec has no "- 状态：auto|todo|manual" line`)
    continue
  }
  const inCode = byId.get(spec.id)
  if (spec.status === 'manual' && inCode !== undefined) problems.push(`${spec.id} is manual in the doc but declared in ${inCode.file}`)
  if (spec.status !== 'manual' && inCode === undefined) problems.push(`${spec.id} is ${spec.status} in the doc but absent from code`)
  if (spec.status !== 'manual' && inCode !== undefined && inCode.kind !== spec.status) {
    problems.push(`${spec.id} is ${spec.status} in the doc but ${inCode.kind} in ${inCode.file} (update the doc when you implement it)`)
  }
}

// Rule 5.
const taskDoc = readFileSync(TASKS, 'utf8')
const cards = new Set([...taskDoc.matchAll(/^## (TASK-\d{2})\b/gm)].map((match) => match[1]))
const referenced = new Set()
for (const dir of ['lib', 'tests']) {
  for (const name of readdirSync(path.join(ROOT, dir)).filter((file) => /\.m?js$/.test(file))) {
    for (const match of readFileSync(path.join(ROOT, dir, name), 'utf8').matchAll(/TASK-\d{2}/g)) referenced.add(match[0])
  }
}
for (const task of referenced) if (!cards.has(task)) problems.push(`${task} is referenced in code but has no card in docs/tasks.md`)

// Rule 2.
const generated = render(cases, specs)
const start = doc.indexOf(BEGIN)
const end = doc.indexOf(END)
if (start < 0 || end < start) problems.push('docs/test-cases.md has no TC-INDEX markers')

if (process.argv.includes('--write')) {
  if (start >= 0 && end > start) {
    writeFileSync(DOC, `${doc.slice(0, start)}${generated}${doc.slice(end + END.length)}`)
    console.log(`tc-index: wrote ${cases.length} code cases into docs/test-cases.md`)
  }
} else if (start >= 0 && end > start && doc.slice(start, end + END.length) !== generated) {
  problems.push('docs/test-cases.md index is stale: run `node tests/tc-index.mjs --write`')
}

for (const problem of problems) console.error(`FAIL ${problem}`)
console.log(`tc-index: ${cases.length} cases in code, ${specs.size} spec sections, ${problems.length} problem(s)`)
process.exitCode = problems.length === 0 ? 0 : 1
